COLUMNS = 16


def build() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    # urut kode; lowercase dipetakan ke glyph uppercase (HUD jadi kapital ala JRPG)
    entries: list[tuple[int, str]] = []
    for ch in GLYPHS:
        entries.append((ord(ch), ch))
    for ch in GLYPHS:
        if ch.isalpha() and ch.isupper():
            entries.append((ord(ch.lower()), ch))
    entries.sort(key=lambda e: e[0])

    rows = (len(entries) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * ADVANCE, rows * LINE_HEIGHT), (0, 0, 0, 0))
    px = atlas.load()
    chars: list[str] = []
    for index, (codepoint, glyph) in enumerate(entries):
        col, row = index % COLUMNS, index // COLUMNS
        ox, oy = col * ADVANCE, row * LINE_HEIGHT
        pattern = GLYPHS[glyph]
        assert len(pattern) == GH, glyph
        for y, line in enumerate(pattern):
            assert len(line) == GW, (glyph, line)
            for x, bit in enumerate(line):
                if bit == "1":
                    px[ox + x, oy + y] = (255, 255, 255, 255)
        chars.append(
            f"char id={codepoint} x={ox} y={oy} width={GW} height={GH} "
            f"xoffset=0 yoffset=0 xadvance={ADVANCE} page=0 chnl=15"
        )

    atlas.save(OUT / "pixel.png")
    header = [
        'info face="ArgaPixel" size=8 bold=0 italic=0 charset="" unicode=1 '
        "stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1",
        f"common lineHeight={LINE_HEIGHT} base={BASE} scaleW={atlas.width} "
        f"scaleH={atlas.height} pages=1 packed=0",
        'page id=0 file="pixel.png"',
        f"chars count={len(chars)}",
    ]
    (OUT / "pixel.fnt").write_text("\n".join(header + chars) + "\n", encoding="utf-8")
    print(f"pixel.png {atlas.width}x{atlas.height}, {len(chars)} glyph "
          f"({len(GLYPHS)} bentuk + lowercase alias)")
    print(f"pixel.fnt: {OUT / 'pixel.fnt'}")


if __name__ == "__main__":
    build()
