ROOT = TOOLS.parent
OUT = ROOT / "game/assets/font"

GW, GH = 5, 7          # ukuran glyph
ADVANCE = 6            # lebar langkah (glyph + 1 px jarak)
LINE_HEIGHT = 8
BASE = 7

