"""Buat font bitmap pixel 5x7 untuk HUD (format BMFont, PNG + .fnt).

Kenapa bitmap: font sistem Godot di-render dengan anti-aliasing, jadi teks HUD
terlihat halus/buram di viewport 480x270 — tidak cocok untuk game 16-bit.
Font ini keras, 1 px per piksel, dan lowercase memakai bentuk uppercase supaya
HUD tetap terbaca sebagai huruf kapital ala JRPG.

Output:
  game/assets/font/pixel.png    atlas glyph (putih, alpha biner)
  game/assets/font/pixel.fnt    deskripsi BMFont (dibaca FontFile.load_bitmap_font)

Jalankan:
    python3 tools/generate_pixel_font.py
"""

